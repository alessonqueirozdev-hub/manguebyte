//! Golden images and scene dumps for tests.
//!
//! A test renders a scene and checks it against two committed files: a PNG
//! compared pixel by pixel with a per-channel tolerance, and the scene's
//! [`dump`](crate::Scene::dump) compared exactly. The tolerance exists
//! because rasterisers round differently on different processors; the dump
//! does not depend on the processor, so it is the exact half of the check.
//!
//! Running the tests with `MANGUEBYTE_BLESS=1` rewrites the files that no
//! longer match, on a developer's machine only: when the `CI` variable is
//! set, blessing is refused and every check fails, so a golden is never
//! regenerated by the machine it is meant to check. On a mismatch the
//! actual image, a difference image and the actual dump are written to a
//! folder for failures, and the error says where.
//!
//! ```no_run
//! use manguebyte_gfx::snapshot::Snapshots;
//! use manguebyte_gfx::{Color, Pixmap, Rect, Renderer, Scene};
//!
//! let mut scene = Scene::new();
//! scene.fill(Rect::new(1.0, 1.0, 6.0, 6.0), Color::hex(0x3366FF));
//! let mut pixels = Pixmap::new(8, 8).expect("small");
//! Renderer::new().render(&scene, &mut pixels, 1.0);
//!
//! let snapshots = Snapshots::new("tests/golden", "target/golden-failures").with_tolerance(2);
//! if let Err(mismatch) = snapshots.check("blue_square", &pixels, &scene.dump()) {
//!     panic!("{mismatch}");
//! }
//! ```

use std::fmt;
use std::fs;
use std::path::{Path, PathBuf};

use crate::color::{Color, PremulColor};
use crate::pixmap::Pixmap;

/// The environment variable that, set to `1`, rewrites golden files.
pub const BLESS_VARIABLE: &str = "MANGUEBYTE_BLESS";

/// Whether checks compare with the golden files or rewrite them.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// Compare, and fail on a difference.
    Compare,
    /// Rewrite the files that differ, and pass.
    Bless,
    /// Blessing was asked for where it is not allowed; every check fails.
    Refused,
}

impl Mode {
    /// The mode the environment asks for: [`Mode::Bless`] when
    /// `MANGUEBYTE_BLESS` is `1`, unless `CI` is set (to anything but empty,
    /// `0` or `false`), which gives [`Mode::Refused`]; otherwise
    /// [`Mode::Compare`].
    pub fn from_env() -> Mode {
        let bless = std::env::var(BLESS_VARIABLE).is_ok_and(|v| v == "1");
        let ci = std::env::var("CI").is_ok_and(|v| !v.is_empty() && v != "0" && v != "false");
        Mode::decide(bless, ci)
    }

    /// The mode for an explicit request and environment.
    pub fn decide(bless: bool, in_ci: bool) -> Mode {
        match (bless, in_ci) {
            (false, _) => Mode::Compare,
            (true, false) => Mode::Bless,
            (true, true) => Mode::Refused,
        }
    }
}

/// How far two images of the same size are apart.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Difference {
    /// The largest difference of one channel of one pixel, from 0 to 255.
    pub max_channel: u8,
    /// Pixels where any channel differs at all.
    pub differing_pixels: usize,
    /// Pixels where a channel differs by more than the tolerance.
    pub failing_pixels: usize,
}

/// Compares two images channel by channel, premultiplied, or returns
/// `None` if their sizes differ.
pub fn compare(expected: &Pixmap, actual: &Pixmap, tolerance: u8) -> Option<Difference> {
    if (expected.width(), expected.height()) != (actual.width(), actual.height()) {
        return None;
    }
    let mut difference = Difference::default();
    for (e, a) in expected
        .data()
        .chunks_exact(4)
        .zip(actual.data().chunks_exact(4))
    {
        let worst = e
            .iter()
            .zip(a)
            .map(|(&x, &y)| x.abs_diff(y))
            .max()
            .unwrap_or(0);
        difference.max_channel = difference.max_channel.max(worst);
        if worst > 0 {
            difference.differing_pixels += 1;
        }
        if worst > tolerance {
            difference.failing_pixels += 1;
        }
    }
    Some(difference)
}

/// An image that shows where two images of the same size differ: red where
/// a channel differs by more than `tolerance`, orange where it differs by
/// less, and the expected image in faint grey elsewhere. `None` if their
/// sizes differ.
pub fn difference_image(expected: &Pixmap, actual: &Pixmap, tolerance: u8) -> Option<Pixmap> {
    if (expected.width(), expected.height()) != (actual.width(), actual.height()) {
        return None;
    }
    let mut out = Pixmap::new(expected.width(), expected.height())?;
    for y in 0..expected.height() {
        for x in 0..expected.width() {
            let (Some(e), Some(a)) = (expected.pixel(x, y), actual.pixel(x, y)) else {
                continue;
            };
            let worst = e
                .to_array()
                .iter()
                .zip(a.to_array())
                .map(|(&p, q)| p.abs_diff(q))
                .max()
                .unwrap_or(0);
            let color = if worst > tolerance {
                Color::rgb(255, 0, 0)
            } else if worst > 0 {
                Color::rgb(255, 160, 0)
            } else {
                let c = e.demultiply();
                let luma = (u32::from(c.r) * 3 + u32::from(c.g) * 6 + u32::from(c.b)) / 10;
                let luma = luma * u32::from(c.a) / 255;
                let v = (255 - luma / 4) as u8;
                Color::rgb(v, v, v)
            };
            out.set_pixel(x, y, PremulColor::from(color));
        }
    }
    Some(out)
}

/// What a passing check did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    /// The files matched; the measured difference is attached.
    Matched(Difference),
    /// The files were written, because blessing was asked for and they
    /// were missing or different.
    Blessed,
}

/// Why a check failed, and where its evidence was written.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Mismatch {
    /// The name of the check.
    pub name: String,
    /// Every problem found, one sentence each.
    pub problems: Vec<String>,
    /// The files written for inspection.
    pub written: Vec<PathBuf>,
}

impl fmt::Display for Mismatch {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "snapshot `{}` does not match:", self.name)?;
        for problem in &self.problems {
            writeln!(f, "  - {problem}")?;
        }
        if !self.written.is_empty() {
            writeln!(f, "  written for inspection:")?;
            for path in &self.written {
                writeln!(f, "    {}", path.display())?;
            }
        }
        write!(
            f,
            "  if the change is intended, run the tests again locally with {BLESS_VARIABLE}=1 \
             and review the new files"
        )
    }
}

impl std::error::Error for Mismatch {}

/// Golden files in one folder, and a folder for the evidence of failures.
#[derive(Debug, Clone)]
pub struct Snapshots {
    dir: PathBuf,
    failures: PathBuf,
    tolerance: u8,
    mode: Mode,
}

impl Snapshots {
    /// Goldens in `dir` (`<name>.png` and `<name>.txt`), evidence of
    /// failures in `failures`, a tolerance of zero, and the mode the
    /// environment asks for ([`Mode::from_env`]).
    pub fn new(dir: impl Into<PathBuf>, failures: impl Into<PathBuf>) -> Self {
        Snapshots {
            dir: dir.into(),
            failures: failures.into(),
            tolerance: 0,
            mode: Mode::from_env(),
        }
    }

    /// The same, allowing each channel of each pixel to differ by up to
    /// `tolerance`.
    pub fn with_tolerance(self, tolerance: u8) -> Self {
        Snapshots { tolerance, ..self }
    }

    /// The same, in `mode` whatever the environment says.
    pub fn with_mode(self, mode: Mode) -> Self {
        Snapshots { mode, ..self }
    }

    /// The tolerance in use.
    pub fn tolerance(&self) -> u8 {
        self.tolerance
    }

    /// The mode in use.
    pub fn mode(&self) -> Mode {
        self.mode
    }

    /// Checks `image` and `dump` against `<name>.png` and `<name>.txt`.
    ///
    /// `name` may use ASCII letters, digits, `_`, `-`, `.` and `@`. Line
    /// endings in the committed dump are read as `\n` whatever the checkout
    /// did to them.
    ///
    /// # Errors
    ///
    /// A [`Mismatch`] naming each problem: a missing file, a dump that
    /// differs (with the first differing line), an image of another size,
    /// pixels beyond the tolerance, a file that could not be read or
    /// written, or blessing refused in CI.
    pub fn check(&self, name: &str, image: &Pixmap, dump: &str) -> Result<Outcome, Mismatch> {
        self.check_parts(name, Some(image), Some(dump))
    }

    /// Checks only `image`, against `<name>.png`; for the same scene drawn
    /// at several scales, whose dump is checked once.
    ///
    /// # Errors
    ///
    /// As for [`check`](Snapshots::check).
    pub fn check_image(&self, name: &str, image: &Pixmap) -> Result<Outcome, Mismatch> {
        self.check_parts(name, Some(image), None)
    }

    /// Checks only `dump`, against `<name>.txt`.
    ///
    /// # Errors
    ///
    /// As for [`check`](Snapshots::check).
    pub fn check_dump(&self, name: &str, dump: &str) -> Result<Outcome, Mismatch> {
        self.check_parts(name, None, Some(dump))
    }

    fn check_parts(
        &self,
        name: &str,
        image: Option<&Pixmap>,
        dump: Option<&str>,
    ) -> Result<Outcome, Mismatch> {
        let mut mismatch = Mismatch {
            name: name.to_owned(),
            problems: Vec::new(),
            written: Vec::new(),
        };
        let valid = !name.is_empty()
            && !name.starts_with('.')
            && name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.' | '@'));
        if !valid {
            mismatch
                .problems
                .push(format!("`{name}` is not a valid snapshot name"));
            return Err(mismatch);
        }
        if self.mode == Mode::Refused {
            mismatch.problems.push(format!(
                "{BLESS_VARIABLE}=1 is set, but so is CI: goldens are regenerated locally, \
                 never in CI"
            ));
            return Err(mismatch);
        }
        let png_path = self.dir.join(format!("{name}.png"));
        let txt_path = self.dir.join(format!("{name}.txt"));

        // The dump.
        let mut dump_differs = false;
        if let Some(dump) = dump {
            let expected_dump = fs::read_to_string(&txt_path)
                .ok()
                .map(|text| text.replace("\r\n", "\n"));
            match &expected_dump {
                None => {
                    dump_differs = true;
                    mismatch
                        .problems
                        .push(format!("{} is missing", txt_path.display()));
                }
                Some(expected) if expected != dump => {
                    dump_differs = true;
                    mismatch.problems.push(first_difference(expected, dump));
                }
                Some(_) => {}
            }
        }

        // The image.
        let mut image_differs = false;
        let mut difference = Difference::default();
        let mut expected_pixels = None;
        if let Some(image) = image {
            match fs::read(&png_path)
                .ok()
                .map(|bytes| Pixmap::decode_png(&bytes))
            {
                None => {
                    image_differs = true;
                    mismatch
                        .problems
                        .push(format!("{} is missing", png_path.display()));
                }
                Some(Err(error)) => {
                    image_differs = true;
                    mismatch
                        .problems
                        .push(format!("{} cannot be read: {error}", png_path.display()));
                }
                Some(Ok(expected)) => {
                    match compare(&expected, image, self.tolerance) {
                        None => {
                            image_differs = true;
                            mismatch.problems.push(format!(
                                "the image is {}x{}, the golden {}x{}",
                                image.width(),
                                image.height(),
                                expected.width(),
                                expected.height()
                            ));
                        }
                        Some(d) => {
                            difference = d;
                            if d.failing_pixels > 0 {
                                image_differs = true;
                                mismatch.problems.push(format!(
                                    "{} pixels differ by more than {} in a channel (at most {})",
                                    d.failing_pixels, self.tolerance, d.max_channel
                                ));
                            }
                        }
                    }
                    expected_pixels = Some(expected);
                }
            }
        }

        if mismatch.problems.is_empty() {
            return Ok(Outcome::Matched(difference));
        }
        if self.mode == Mode::Bless {
            // Only what differs is rewritten, so blessing does not churn
            // files whose encoding alone would change.
            let mut failed = Vec::new();
            if let Err(error) = fs::create_dir_all(&self.dir) {
                failed.push(format!("cannot create {}: {error}", self.dir.display()));
            }
            if let (Some(dump), true) = (dump, dump_differs) {
                if let Err(error) = fs::write(&txt_path, dump) {
                    failed.push(format!("cannot write {}: {error}", txt_path.display()));
                }
            }
            if let (Some(image), true) = (image, image_differs) {
                if let Err(error) = write_png(&png_path, image) {
                    failed.push(error);
                }
            }
            if failed.is_empty() {
                return Ok(Outcome::Blessed);
            }
            mismatch.problems = failed;
            return Err(mismatch);
        }

        // Evidence for whoever reads the failure.
        if let Err(error) = fs::create_dir_all(&self.failures) {
            mismatch.problems.push(format!(
                "cannot create {}: {error}",
                self.failures.display()
            ));
            return Err(mismatch);
        }
        if let (Some(image), true) = (image, image_differs) {
            let actual_png = self.failures.join(format!("{name}.actual.png"));
            match write_png(&actual_png, image) {
                Ok(()) => mismatch.written.push(actual_png),
                Err(error) => mismatch.problems.push(error),
            }
            if let Some(expected) = &expected_pixels {
                if let Some(diff) = difference_image(expected, image, self.tolerance) {
                    let diff_png = self.failures.join(format!("{name}.diff.png"));
                    match write_png(&diff_png, &diff) {
                        Ok(()) => mismatch.written.push(diff_png),
                        Err(error) => mismatch.problems.push(error),
                    }
                }
            }
        }
        if let (Some(dump), true) = (dump, dump_differs) {
            let actual_txt = self.failures.join(format!("{name}.actual.txt"));
            match fs::write(&actual_txt, dump) {
                Ok(()) => mismatch.written.push(actual_txt),
                Err(error) => mismatch
                    .problems
                    .push(format!("cannot write {}: {error}", actual_txt.display())),
            }
        }
        Err(mismatch)
    }
}

fn write_png(path: &Path, image: &Pixmap) -> Result<(), String> {
    let bytes = image
        .encode_png()
        .map_err(|error| format!("cannot encode {}: {error}", path.display()))?;
    fs::write(path, bytes).map_err(|error| format!("cannot write {}: {error}", path.display()))
}

/// A sentence naming the first line where two dumps differ.
fn first_difference(expected: &str, actual: &str) -> String {
    let mut expected_lines = expected.lines();
    let mut actual_lines = actual.lines();
    let mut line = 1;
    loop {
        match (expected_lines.next(), actual_lines.next()) {
            (Some(e), Some(a)) if e == a => line += 1,
            (Some(e), Some(a)) => {
                return format!(
                    "the dump differs at line {line}:\n      golden: {e}\n      actual: {a}"
                );
            }
            (Some(e), None) => {
                return format!("the dump ends before line {line}, which the golden has: {e}");
            }
            (None, Some(a)) => {
                return format!("the dump has a line {line} the golden does not: {a}");
            }
            (None, None) => {
                return "the dumps differ only in their line endings or final newline".to_owned();
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(name: &str) -> PathBuf {
        // One folder per test and process, removed by the test at its end.
        let dir = std::env::temp_dir().join(format!(
            "manguebyte-gfx-snapshot-{name}-{}",
            std::process::id()
        ));
        let _ = fs::remove_dir_all(&dir);
        dir
    }

    fn square(color: Color) -> Pixmap {
        let mut p = Pixmap::new(3, 2).expect("small");
        p.fill(color);
        p
    }

    #[test]
    fn blessing_is_allowed_only_outside_ci() {
        assert_eq!(Mode::decide(false, false), Mode::Compare);
        assert_eq!(Mode::decide(false, true), Mode::Compare);
        assert_eq!(Mode::decide(true, false), Mode::Bless);
        assert_eq!(Mode::decide(true, true), Mode::Refused);
    }

    #[test]
    fn differences_are_measured_per_channel() {
        let a = square(Color::rgb(10, 20, 30));
        let mut b = a.clone();
        b.set_pixel(1, 1, PremulColor::new(13, 20, 30, 255).expect("valid"));
        b.set_pixel(2, 0, PremulColor::new(10, 20, 31, 255).expect("valid"));
        assert_eq!(
            compare(&a, &b, 1),
            Some(Difference {
                max_channel: 3,
                differing_pixels: 2,
                failing_pixels: 1,
            })
        );
        assert_eq!(compare(&a, &Pixmap::new(2, 3).expect("small"), 255), None);
        let diff = difference_image(&a, &b, 1).expect("same size");
        assert_eq!(
            diff.pixel(1, 1).map(PremulColor::to_array),
            Some([255, 0, 0, 255])
        );
        assert_eq!(
            diff.pixel(2, 0).map(PremulColor::to_array),
            Some([255, 160, 0, 255])
        );
    }

    #[test]
    fn a_bless_then_a_compare_passes_and_a_change_fails_with_evidence() {
        let dir = scratch("golden");
        let failures = scratch("failures");
        let image = square(Color::rgb(1, 2, 3));
        let blessing = Snapshots::new(&dir, &failures).with_mode(Mode::Bless);
        assert_eq!(
            blessing.check("case", &image, "fill\n"),
            Ok(Outcome::Blessed)
        );

        let checking = Snapshots::new(&dir, &failures).with_mode(Mode::Compare);
        assert_eq!(
            checking.check("case", &image, "fill\n"),
            Ok(Outcome::Matched(Difference::default()))
        );

        // A golden checked out with Windows line endings still matches.
        fs::write(dir.join("case.txt"), "fill\r\n").expect("write");
        assert!(checking.check("case", &image, "fill\n").is_ok());

        let changed = square(Color::rgb(9, 2, 3));
        let mismatch = checking
            .check("case", &changed, "stroke\n")
            .expect_err("both differ");
        assert_eq!(mismatch.problems.len(), 2, "{mismatch}");
        assert!(mismatch.problems[0].contains("golden: fill"), "{mismatch}");
        assert!(mismatch.problems[1].starts_with("6 pixels differ by more than 0"));
        let names: Vec<String> = mismatch
            .written
            .iter()
            .filter_map(|p| p.file_name().map(|n| n.to_string_lossy().into_owned()))
            .collect();
        assert_eq!(
            names,
            ["case.actual.png", "case.diff.png", "case.actual.txt"]
        );
        let written =
            Pixmap::decode_png(&fs::read(&mismatch.written[0]).expect("read")).expect("a PNG");
        assert_eq!(written, changed);

        // Within the tolerance it passes, and reports what it measured.
        let tolerant = checking.clone().with_tolerance(8);
        assert_eq!(
            tolerant.check("case", &changed, "fill\n"),
            Ok(Outcome::Matched(Difference {
                max_channel: 8,
                differing_pixels: 6,
                failing_pixels: 0,
            }))
        );
        let _ = fs::remove_dir_all(&dir);
        let _ = fs::remove_dir_all(&failures);
    }

    #[test]
    fn missing_goldens_refusals_and_bad_names_fail() {
        let dir = scratch("missing");
        let failures = scratch("missing-failures");
        let image = square(Color::WHITE);
        let checking = Snapshots::new(&dir, &failures).with_mode(Mode::Compare);
        let mismatch = checking
            .check("absent", &image, "x\n")
            .expect_err("missing");
        assert_eq!(mismatch.problems.len(), 2);
        assert!(mismatch.to_string().contains("MANGUEBYTE_BLESS=1"));
        let refused = Snapshots::new(&dir, &failures).with_mode(Mode::Refused);
        assert!(refused.check("absent", &image, "x\n").is_err());
        assert!(!dir.join("absent.png").exists());
        for bad in ["", "../escape", "a/b", ".hidden", "sp ace"] {
            assert!(checking.check(bad, &image, "").is_err(), "{bad:?}");
        }
        let _ = fs::remove_dir_all(&dir);
        let _ = fs::remove_dir_all(&failures);
    }
}
